"""
main.py — Job Posting Watcher Entry Point
===========================================
This is the main script that ties everything together and runs the watcher loop.

What it does:
  1. Loads configuration (config.yaml + urls.yaml)
  2. Initializes the database (SQLite), matcher (GenAI), and notifier (Gmail)
  3. Runs the first check cycle immediately
  4. Then repeats every N minutes (configured in config.yaml)
  5. On Ctrl+C or kill signal, shuts down gracefully

Each cycle:
  - For each portal URL in urls.yaml:
      a. Pick the right scraper for the portal type
      b. Scrape all job postings from that portal
      c. Check which jobs are NEW (not seen in SQLite database)
      d. For new Workday jobs, fetch full descriptions
      e. Send new jobs to GenAI matcher for scoring
      f. Save all jobs to database with their scores
      g. Collect jobs that score >= threshold
  - If any matches found: send one digest email with all matches
  - Log a summary (X portals checked, Y matches found)

Usage:
  python main.py

  Make sure config.yaml is configured and env vars are set before running.
  First run may open a browser for Gmail OAuth consent.
"""

import argparse
import logging
import signal
import subprocess
import sys
import time
from datetime import date
from pathlib import Path
from urllib.parse import urlparse

import schedule
import yaml

from config import load_config, load_urls
from services.db import JobDatabase
from services.logging_setup import setup_logging
from services.matcher import JobMatcher
from services.notifier import EmailNotifier
from services.resume_builder import ResumeBuilder
from scrapers import get_scraper

logger = logging.getLogger("jobwatcher")

# Global flag for graceful shutdown
_shutdown = False   # Set to True when Ctrl+C or SIGTERM is received

# Path to per-portal location facets (generated by scripts/discover_locations.py)
_LOCATIONS_YAML = Path(__file__).parent / "config" / "workday_locations.yaml"


def _load_workday_locations() -> dict:
    """Load per-portal Workday location facets from config/workday_locations.yaml.

    Returns:
        Dict keyed by portal path (e.g., "gea.wd3.myworkdayjobs.com/en-US/GEACareers")
        with facet info, or empty dict if file doesn't exist.
    """
    if not _LOCATIONS_YAML.exists():
        logger.warning("No workday_locations.yaml found — run: python scripts/discover_locations.py")
        return {}
    with open(_LOCATIONS_YAML) as f:
        return yaml.safe_load(f) or {}


def _get_facets_for_url(url: str, locations: dict) -> list[dict]:
    """Look up appliedFacets for a Workday portal URL from the locations config.

    Returns a list of single-facet dicts so each facet type can be queried
    separately (avoids Workday's AND logic between different facet types).

    Args:
        url:       The portal URL from urls.yaml.
        locations: The loaded workday_locations.yaml data.

    Returns:
        A list of dicts, each with one facet type. e.g.:
        [{"locationCountry": ["id1"]}, {"locations": ["id2", "id3"]}]
        Returns empty list if no facets configured.
    """
    parsed = urlparse(url)
    key = f"{parsed.hostname}{parsed.path.rstrip('/')}"
    portal = locations.get(key)
    if not portal:
        return []

    return [
        {param: [entry["id"] for entry in entries]}
        for param, entries in portal.items()
    ]


def _signal_handler(sig, frame):
    """Handle Ctrl+C (SIGINT) and kill (SIGTERM) signals.

    Instead of crashing immediately, sets the _shutdown flag so the main loop
    can finish the current work and clean up properly (close browser, DB, etc.).

    This is registered via signal.signal() in main() — it tells the OS:
    "When this process receives SIGINT or SIGTERM, call this function."
    """
    global _shutdown
    logger.info("Shutdown requested (signal %s)", sig)
    _shutdown = True


# Scrapers that also accept a `cities` filter from their config section.
_CITY_SCRAPERS = {"greenhouse", "lever", "ashby"}


def _create_scraper(scraper_type: str, config: dict, url: str, wd_locations: dict):
    """Create the appropriate scraper instance for a given URL.

    `max_age_days` is a single shared setting (config["max_age_days"], default 10)
    applied to every scraper. Workday additionally gets its per-portal location
    facets; the Greenhouse/Lever/Ashby scrapers additionally get a `cities` filter.

    Args:
        scraper_type:  The scraper type string from urls.yaml (e.g. "workday", "amazon").
        config:        The loaded config.yaml dictionary.
        url:           The portal URL being scraped.
        wd_locations:  Per-portal Workday location facets.

    Returns:
        A scraper instance ready to call .scrape(url).
    """
    max_age_days = config.get("max_age_days", 10)

    if scraper_type == "workday":
        facet_list = _get_facets_for_url(url, wd_locations)
        return get_scraper(scraper_type, facet_list=facet_list, max_age_days=max_age_days)
    if scraper_type in _CITY_SCRAPERS:
        cities = config.get(scraper_type, {}).get("cities")
        return get_scraper(scraper_type, cities=cities, max_age_days=max_age_days)
    return get_scraper(scraper_type, max_age_days=max_age_days)


def _resume_eligible(scraper: str, enabled_scrapers: set) -> bool:
    """Whether a resume should be generated for a job from this scraper.

    Driven entirely by config's resume_builder.enabled_scrapers:
      - empty list  → no resumes for anyone
      - otherwise   → generate for jobs whose scraper is listed, plus jobs tagged
                      "always" (e.g. older DB rows with no stored scraper), so we
                      don't silently stop generating for them.
    """
    if not enabled_scrapers:
        return False
    return scraper == "always" or scraper in enabled_scrapers


def _notify_pending(db: JobDatabase, notifier: EmailNotifier,
                    resume_builder: ResumeBuilder | None = None, attach_resume: bool = False,
                    enabled_scrapers: set | None = None):
    """Send notifications for jobs that were scored but never emailed.

    This handles the case where a previous run saved jobs to the DB and then
    crashed or exited before the email was sent. Called once at startup before
    the first cycle.
    """
    enabled_scrapers = enabled_scrapers or set()
    pending_matches, pending_filtered = db.get_unnotified_jobs()
    if not pending_matches and not pending_filtered:
        return

    logger.info("Found %d matches and %d filtered unnotified jobs from a previous run",
                len(pending_matches), len(pending_filtered))

    from scrapers.base import JobPosting

    def _rows_to_tuples(rows):
        result = []
        for row in rows:
            job = JobPosting(
                job_id=row["job_id"],
                job_num=row["job_num"] or "",
                title=row["title"],
                company=row["company"],
                location=row["location"] or "",
                description=row.get("job_description") or "",
                url=row["url"],
                posted_date=None,
                # Pre-column rows have NULL scraper; mark them "always" so they still
                # get a resume (we can't know their true source).
                scraper=row.get("scraper") or "always",
            )
            result.append((job, row["match_score"], row["match_reason"] or ""))
        return result

    matches = _rows_to_tuples(pending_matches)
    filtered = _rows_to_tuples(pending_filtered)

    pdfs = {}
    if attach_resume and resume_builder and matches:
        # Only generate for jobs that don't already have a resume (resume_name NULL) —
        # a prior run may have generated them before crashing pre-email.
        needs_resume = {row["job_id"] for row in pending_matches if not row.get("resume_name")}
        gen_matches = [
            (job, s, r) for job, s, r in matches
            if _resume_eligible(job.scraper, enabled_scrapers) and job.job_id in needs_resume
        ]
        if gen_matches:
            pdfs = resume_builder.generate_for_matches(gen_matches)

    try:
        notifier.send_digest(matches, filtered=filtered, attachments=pdfs or None)
        for job, _, _ in matches + filtered:
            db.mark_notified(job.job_id)
        logger.info("Sent pending notification for %d matches + %d filtered", len(matches), len(filtered))
    except Exception as e:
        logger.error("Failed to send pending notifications: %s", e)


def run_cycle(config: dict, db: JobDatabase, matcher: JobMatcher, notifier: EmailNotifier,
              log_dir: str, run_no: int,
              workday_locations: dict | None = None, resume_builder: ResumeBuilder | None = None):
    """Run one full check cycle: scrape all portals, match new jobs, send digest.

    This function is called once immediately at startup, then every N minutes
    by the schedule library.

    Args:
        config:             The loaded config.yaml dictionary.
        db:                 The SQLite database for deduplication.
        matcher:            The GenAI matcher for scoring jobs.
        notifier:           The email notifier for sending digests.
        log_dir:            Absolute log folder, passed on to apply.py.
        run_no:             This watcher's run number; apply.py logs under the same number.
        workday_locations:  Per-portal facets from workday_locations.yaml.
        resume_builder:     Optional resume builder for generating tailored resumes.
    """
    urls = load_urls()  # Re-read urls.yaml each cycle (in case you add new portals)
    delay = config["schedule"].get("delay_between_sites_seconds", 5)
    digest_mode = config.get("email", {}).get("digest_mode", "per_company")
    attach_resume = config.get("resume_builder", {}).get("attach_resume", False)
    enabled_scrapers = set(config.get("resume_builder", {}).get("enabled_scrapers") or [])
    wd_locations = workday_locations or {}
    auto_apply = config.get("apply", {}).get("auto_apply", False)
    total_matches = 0
    total_filtered = 0

    def _run_auto_apply(job_ids: list[str]):
        """Fire apply.py for the given job IDs right after an email is sent."""
        if not auto_apply or not job_ids:
            return
        ids_csv = ",".join(job_ids)
        logger.info("Auto-apply: passing %d job(s) to apply.py", len(job_ids))
        try:
            subprocess.run(
                [sys.executable, "apply.py", "--job-ids", ids_csv, "--log-dir", log_dir, "--run-no", str(run_no)],
                cwd=str(Path(__file__).parent),
            )
        except Exception as e:
            logger.error("Auto-apply failed: %s", e)

    def _flush_digest(matches: list, filtered: list, company: str | None = None):
        """Sort, build resume PDFs, email the digest, mark notified, then auto-apply.

        Shared by all three send paths (per-company, aggregated early-flush,
        aggregated end-of-cycle) so they can't drift apart. No-op if empty.
        """
        if not matches and not filtered:
            return
        matches.sort(key=lambda x: (x[1], x[0].posted_date or date.min), reverse=True)
        filtered.sort(key=lambda x: (x[1], x[0].posted_date or date.min), reverse=True)
        pdfs = {}
        if attach_resume and resume_builder and matches:
            # Only generate/attach resumes for jobs from enabled scrapers (config).
            gen_matches = [(job, s, r) for job, s, r in matches if _resume_eligible(job.scraper, enabled_scrapers)]
            if gen_matches:
                pdfs = resume_builder.generate_for_matches(gen_matches)
        notifier.send_digest(matches, filtered=filtered, company=company, attachments=pdfs or None)
        for job, _, _ in matches + filtered:
            db.mark_notified(job.job_id)
        _run_auto_apply([job.job_id for job, _, _ in matches + filtered])

    # For aggregated mode: accumulate across all portals, send once at the end
    all_matches = []
    all_filtered = []

    for scraper_type, url in urls:
        if _shutdown:
            break  # Stop checking if shutdown was requested

        logger.info("Checking [%s] %s", scraper_type, url)
        try:
            scraper = _create_scraper(scraper_type, config, url, wd_locations)

            # Step 1: Scrape all jobs from this portal
            jobs = scraper.scrape(url)
            for job in jobs:
                job.scraper = scraper_type  # tag source for per-scraper gating (e.g. resumes)

            # Step 2: Filter to new jobs (also updates last_seen for known ones)
            new_jobs = db.filter_new(jobs)
            logger.info("[%s] %s — %d jobs, %d new", scraper_type, url, len(jobs), len(new_jobs))

            if new_jobs:
                # Step 3: Fetch full descriptions if the scraper supports it
                if hasattr(scraper, "enrich_descriptions"):
                    scraper.enrich_descriptions(new_jobs)

                # Step 4: Score new jobs against user profile via GenAI
                scored = matcher.match_jobs(new_jobs)

                # Step 5: Save scored jobs and split into matches vs filtered
                matches = []
                filtered = []
                for job, score, reason in scored:
                    is_match = score >= matcher.threshold
                    db.save_job(job, match_score=score, match_reason=reason, matched=is_match)
                    if is_match:
                        matches.append((job, score, reason))
                        logger.info(
                            "  MATCH: %s at %s (score=%d)", job.title, job.company, score
                        )
                    else:
                        filtered.append((job, score, reason))

                # Step 6: send now (per-company) or accumulate for the aggregated digest.
                # _flush_digest sorts, builds PDFs, emails, marks notified, and auto-applies.
                if digest_mode == "per_company":
                    _flush_digest(matches, filtered, company=new_jobs[0].company)
                else:
                    all_matches.extend(matches)
                    all_filtered.extend(filtered)

                    # Flush early if accumulated matches hit the threshold
                    agg_threshold = config.get("email", {}).get("aggregated_threshold", 0)
                    if agg_threshold > 0 and len(all_matches) >= agg_threshold:
                        logger.info("Aggregated threshold reached (%d matches >= %d) — sending early digest",
                                    len(all_matches), agg_threshold)
                        _flush_digest(all_matches, all_filtered)
                        all_matches.clear()
                        all_filtered.clear()

                total_matches += len(matches)
                total_filtered += len(filtered)

            # Clean up scraper resources (e.g., httpx client connections)
            scraper.close()

        except RuntimeError:
            raise  # Fatal errors (e.g. GenAI retries exhausted) — stop the scraper
        except Exception as e:
            logger.error("Error processing %s: %s", url, e)

        # Be respectful: wait between portal checks to avoid getting blocked
        if not _shutdown:
            time.sleep(delay)

    # Aggregated mode: send one combined email after all portals are processed
    if digest_mode == "aggregated":
        _flush_digest(all_matches, all_filtered)

    logger.info(
        "Cycle complete: %d portals checked, %d matches, %d filtered",
        len(urls), total_matches, total_filtered,
    )


def main():
    """Main entry point: initialize everything and start the scheduler loop."""
    # Register signal handlers so Ctrl+C and kill trigger graceful shutdown
    # These tell the OS: "call _signal_handler when this process gets these signals"
    signal.signal(signal.SIGINT, _signal_handler)   # Ctrl+C
    signal.signal(signal.SIGTERM, _signal_handler)   # kill command

    parser = argparse.ArgumentParser(description="Scrape, score, and email job digests on a schedule")
    parser.add_argument("--log-dir", default="logs", help="Folder for main_<run_no>.log files (default: ./logs)")
    log_dir = str(Path(parser.parse_args().log_dir).resolve())  # absolute: apply.py runs from the project root
    run_no = setup_logging(log_dir, "main")

    # Initialize all components
    logger.info("Loading configuration...")
    config = load_config()

    logger.info("Initializing database...")
    db = JobDatabase()

    logger.info("Initializing matcher...")
    matcher = JobMatcher(config)

    logger.info("Initializing notifier...")
    notifier = EmailNotifier(config)

    # Initialize resume builder if attach_resume is enabled
    rb_cfg = config.get("resume_builder", {})
    resume_builder = None
    if rb_cfg.get("attach_resume", False):
        logger.info("Initializing resume builder (attach_resume=true)...")
        resume_builder = ResumeBuilder(config, db)

    logger.info("Loading Workday location facets...")
    workday_locations = _load_workday_locations()

    # Read schedule interval from config (default: every 60 minutes)
    interval = config["schedule"].get("interval_minutes", 60)
    logger.info("Scheduling checks every %d minutes", interval)

    # Send any notifications that failed in a previous run
    enabled_scrapers = set(rb_cfg.get("enabled_scrapers") or [])
    _notify_pending(db, notifier, resume_builder, rb_cfg.get("attach_resume", False), enabled_scrapers)

    # Run the first check immediately (don't wait for the timer)
    run_cycle(config, db, matcher, notifier, log_dir, run_no, workday_locations, resume_builder)

    # Schedule all subsequent checks using the 'schedule' library
    schedule.every(interval).minutes.do(run_cycle, config, db, matcher, notifier, log_dir, run_no,
                                        workday_locations, resume_builder)

    # Main loop: check if any scheduled jobs need to run, every second
    logger.info("Watcher running. Press Ctrl+C to stop.")
    while not _shutdown:
        schedule.run_pending()  # Runs run_cycle() when the timer fires
        time.sleep(1)           # Check every second (low CPU usage)

    # Graceful shutdown: clean up all resources
    logger.info("Shutting down...")
    db.close()               # Close SQLite connection
    logger.info("Goodbye.")


if __name__ == "__main__":
    main()
